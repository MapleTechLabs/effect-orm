import { getCollection } from "astro:content";
import type { SidebarSection } from "@cloudflare/nimbus-docs/types";
import { dialects, groups, pagesFor } from "../../scripts/sidebar.mjs";

export interface SiteSection extends SidebarSection {
  /** A dialect's section, or a shared one (Benchmarks, Reference). */
  kind: "dialect" | "shared";
}

const slugOf = (page: { file: string; slug?: string }) => page.slug ?? page.file.replace(/\.md$/, "");

/**
 * The header tabs: one per dialect, then one per shared group. Built from
 * scripts/sidebar.mjs rather than Nimbus's `getSidebarSections`, which only
 * makes tabs of autogenerated folders. A dialect tab points at the guide you
 * are reading in that dialect when it has one (`/postgres/queries/joins/` →
 * `/clickhouse/queries/joins/`), and at the dialect's first page otherwise.
 */
export async function getSiteSections(currentSlug: string): Promise<SiteSection[]> {
  const [, current = "", ...rest] = currentSlug.split("/");
  const guide = dialects.some((d) => d.id === current) ? rest.join("/") : "";
  const ids = guide ? new Set((await getCollection("docs")).map((entry) => entry.id)) : new Set<string>();

  const dialectTabs = dialects.map((dialect): SiteSection => {
    const first = groups.find((g) => !g.shared && pagesFor(g, dialect).length > 0)!;
    const href =
      guide && ids.has(`${dialect.id}/${guide}`)
        ? `/${dialect.id}/${guide}/`
        : `/${dialect.id}/${first.dir}/${slugOf(pagesFor(first, dialect)[0])}/`;
    return { label: dialect.label, href, isActive: current === dialect.id, kind: "dialect" };
  });
  const sharedTabs = groups
    .filter((g) => g.shared)
    .map((group): SiteSection => ({
      label: group.label as string,
      href: `/${group.dir}/${slugOf(group.pages[0])}/`,
      isActive: current === group.dir,
      kind: "shared",
    }));
  return [...dialectTabs, ...sharedTabs];
}
